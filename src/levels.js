export function levelMaxScore(level) {
  let sum = level.blocks.length * 150 + level.pigs.length * 900;
  sum += level.birds * 1000;
  return sum;
}

export function levelStars(level, score) {
  const max = levelMaxScore(level);
  if (score >= max * 0.75) return 3;
  if (score >= max * 0.55) return 2;
  if (score >= max * 0.35) return 1;
  return 0;
}
